import fs from "node:fs";
import path from "node:path";
import ts from "typescript";
const root = path.resolve(import.meta.dirname, "../../..");
const source = fs.readFileSync(path.join(root, "lib/apps.ts"), "utf8");
const compiled = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS },
}).outputText;
const mod = { exports: {} };
new Function("exports", compiled)(mod.exports);
const catalog = mod.exports.apps.map((app) => ({
  ...app,
  group: /Game|Sim/.test(app.category)
    ? "Games"
    : app.category === "Audio"
      ? "Audio"
      : "Tools",
}));
for (const app of catalog)
  if (new URL(app.url).protocol !== "https:")
    throw new Error(`Unsafe URL: ${app.slug}`);
fs.mkdirSync(path.join(root, "apps/mobile/src"), { recursive: true });
fs.writeFileSync(
  path.join(root, "apps/mobile/src/catalog.json"),
  JSON.stringify(catalog, null, 2) + "\n",
);
fs.mkdirSync(path.join(root, "apps/mobile/assets/shots"), { recursive: true });
for (const app of catalog)
  if (app.shot)
    fs.copyFileSync(
      path.join(root, "public", app.shot),
      path.join(root, "apps/mobile/assets", app.shot),
    );
fs.writeFileSync(
  path.join(root, "apps/mobile/src/images.ts"),
  "// Generated by npm run catalog.\nexport const images: Record<string, number> = {\n" +
    catalog
      .filter((a) => a.shot)
      .map((a) => `  '${a.slug}': require('../assets${a.shot}'),`)
      .join("\n") +
    "\n};\n",
);
console.log(`Bundled ${catalog.length} products with offline artwork.`);
